import type { EnvKey, ServerEnv } from "@/server/env";
import type { IntegrationDefinition } from "./types";

const need = (env: ServerEnv, ...keys: EnvKey[]): EnvKey[] =>
  keys.filter((k) => env[k] === undefined || env[k] === "");

/** Provider selected but its credentials are absent → report the credential keys as missing. */
const provider = (
  env: ServerEnv,
  selector: EnvKey,
  requirements: Record<string, EnvKey[]>,
): EnvKey[] => {
  const selected = env[selector];
  if (!selected || selected === "none") return [selector];
  return need(env, ...(requirements[selected as string] ?? []));
};

